// A11.0 / A13.0 inventories: number inputs and help-tip coverage of editor controls, from source.
// Static approximation (a control counts as tipped when a <q-tooltip> sits inside its element block).
// Usage: node test/inventory.mjs docs/roadmap/DNDSheet-Control-Inventory.md (omit the path to print)
import fs from 'node:fs'
import path from 'node:path'

const CONTROLS = ['q-input', 'q-select', 'q-toggle', 'q-checkbox', 'q-slider', 'q-range', 'q-option-group', 'q-btn-toggle', 'formula-field']
const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)])
const files = walk('src').filter((f) => f.endsWith('.vue')).sort()
const numbers = []
// A11.1 classes. Array-item monster facts stay blocked until stable-id paths exist (field-types.ts A9.2 note).
function classify(rel, model, block = '') {
  if (rel.includes('/character/')) return 'literal: character sheet'
  if (/A4LayerStudio|widgets\/|portrait|editorStore/.test(rel + model)) return 'literal: presentation'
  if (/SpellsEditor|NewSpellDialog/.test(rel)) return 'literal: spell data'
  if (/CrAnnotationCard/.test(rel)) return 'literal: CR annotation'
  if (/runehammerTrack|ev\.round/.test(model)) return 'literal: tracker state'
  if (/ClassCastingEditor/.test(rel) && /slots\[/.test(block)) return 'literal: slot table (field-types exception)'
  if (/composer\//.test(rel)) return 'binding-capable: composer draft (owned by composer apply)'
  if (/^(ap|phaseCfg|lang)\./.test(model)) return 'binding-capable: blocked on identity migration'
  return 'review'
}
const perFile = []
for (const file of files) {
  const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/)
  const rel = path.relative('.', file).split(path.sep).join('/')
  let controls = 0, tipped = 0
  lines.forEach((line, index) => {
    if (/type="number"/.test(line)) {
      // Read the label from this input's own element, not a neighbour's.
      let start = index
      while (start > 0 && start > index - 12 && !/<(q-input|input)\b/.test(lines[start])) start--
      let stop = index
      while (stop < lines.length - 1 && stop < index + 12 && !/\/>\s*$|<\/q-input>/.test(lines[stop])) stop++
      const block = lines.slice(start, stop + 1).join(' ')
      const model = block.match(/v-model(?:\.number)?="([^"]+)"/)?.[1] || ''
      const label = block.match(/\blabel="([^"]+)"/)?.[1] || block.match(/:label="([^"]+)"/)?.[1] || ''
      numbers.push({ rel, line: index + 1, model, label, kind: classify(rel, model, block) })
    }
    const tag = CONTROLS.find((name) => new RegExp(`<${name}(\\s|>|$)`).test(line))
    if (!tag) return
    controls++
    let end = index
    // The element ends at its closing tag, or at a self-closing line once no child element is still open.
    for (let j = index; j < Math.min(lines.length, index + 40); j++) {
      end = j
      if (lines[j].includes(`</${tag}>`)) break
      const openChild = lines.slice(index + 1, j + 1).some((l) => /<[a-z]/.test(l) && !/\/>\s*$/.test(l))
      if (/\/>\s*$/.test(lines[j]) && !openChild) break
    }
    if (/<q-tooltip|v-help=/.test(lines.slice(index, end + 1).join(' '))) tipped++
  })
  if (controls) perFile.push({ rel, controls, tipped })
}
const total = perFile.reduce((a, f) => a + f.controls, 0)
const tippedTotal = perFile.reduce((a, f) => a + f.tipped, 0)
const pct = (a, b) => (b ? ((a / b) * 100).toFixed(1) : '0.0') + ' %'
const out = []
out.push('# DNDSheet control inventory', '', 'Generated by `node test/inventory.mjs` from source. Static approximation: a control counts as tipped when a `<q-tooltip>` or a `v-help` sits inside its element block.', '')
out.push('## A13.0 help-tip coverage baseline', '', '| Controls | With help tip | Coverage |', '|---|---|---|', `| ${total} | ${tippedTotal} | ${pct(tippedTotal, total)} |`, '')
out.push('| File | Controls | Tipped | Coverage |', '|---|---|---|---|')
for (const f of perFile.sort((a, b) => b.controls - a.controls)) out.push(`| \`${f.rel}\` | ${f.controls} | ${f.tipped} | ${pct(f.tipped, f.controls)} |`)
out.push('', `## A11.0 number inputs (${numbers.length})`, '', '| File | Line | Model | Label | A11.1 class |', '|---|---|---|---|---|')
for (const n of numbers) out.push(`| \`${n.rel}\` | ${n.line} | \`${n.model || '?'}\` | ${n.label || '?'} | ${n.kind} |`)
const target = process.argv[2]
if (target) fs.writeFileSync(target, out.join('\n') + '\n')
else process.stdout.write(out.join('\n') + '\n')
