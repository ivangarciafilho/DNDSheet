<template>
  <q-dialog v-model="isOpen" persistent>
    <q-card style="width: 780px; max-width: 95vw; max-height: 90vh" class="column">
      <q-card-section class="bg-primary text-white row items-center q-pb-sm">
        <q-icon name="auto_awesome" size="sm" class="q-mr-sm" />
        <div class="text-h6">AI Statblock Ingest Studio</div>
        <q-space />
        <q-btn icon="close" flat round dense v-close-popup />
      </q-card-section>

      <q-card-section class="col scroll q-pt-md">
        <div class="text-caption text-grey-7 q-mb-sm">
          Paste any raw text or markdown containing a statblock generated by ChatGPT, Claude, DeepSeek, or local LLMs.
          The ingest pipeline extracts JSON blocks, applies schema migration, and auto-corrects references.
        </div>

        <div class="row q-gutter-xs q-mb-sm">
          <q-btn
            size="sm"
            outline
            color="primary"
            label="Load Dragon Sample"
            icon="mdi-dragon"
            @click="loadSample('dragon')"
          />
          <q-btn
            size="sm"
            outline
            color="secondary"
            label="Load Archmage Sample"
            icon="mdi-wizard-hat"
            @click="loadSample('archmage')"
          />
          <q-space />
          <q-btn
            size="sm"
            flat
            color="grey-7"
            label="Clear"
            icon="clear"
            @click="rawInput = ''"
          />
        </div>

        <q-input
          v-model="rawInput"
          type="textarea"
          outlined
          autogrow
          rows="10"
          placeholder="Paste AI response here (e.g. ```json { ... } ``` or raw JSON)..."
          class="font-mono text-body2"
        />

        <!-- Live Analysis Banner -->
        <div v-if="rawInput.trim().length > 0" class="q-mt-md">
          <div v-if="ingestResult.success && ingestResult.monster" class="q-pa-sm rounded-borders bg-green-1 text-green-10 border-green">
            <div class="row items-center q-gutter-sm">
              <q-icon name="check_circle" color="positive" size="sm" />
              <div class="text-subtitle2">Statblock Validated: {{ ingestResult.monster.name }}</div>
              <q-badge color="teal">CR {{ ingestResult.monster.CR }}</q-badge>
              <q-badge color="purple">{{ ingestResult.monster.size }} {{ ingestResult.monster.type }}</q-badge>
              <q-badge v-if="ingestResult.issuesFixed > 0" color="orange">
                {{ ingestResult.issuesFixed }} Auto-Fixes Applied
              </q-badge>
            </div>
            <div class="row q-gutter-md q-mt-xs text-caption">
              <span><strong>AC:</strong> {{ ingestResult.monster.AC }}</span>
              <span><strong>HP:</strong> {{ ingestResult.monster.HP.HD }}d{{ ingestResult.monster.HP.type }} + {{ ingestResult.monster.HP.modifier }}</span>
              <span><strong>Attacks:</strong> {{ ingestResult.monster.attacks?.length ?? 0 }}</span>
              <span><strong>Actions:</strong> {{ ingestResult.monster.actions?.length ?? 0 }}</span>
              <span><strong>Traits:</strong> {{ ingestResult.monster.traits?.length ?? 0 }}</span>
            </div>
          </div>

          <div v-else class="q-pa-sm rounded-borders row items-center q-gutter-sm" style="background: rgba(244, 67, 54, 0.12); border: 1px solid rgba(244, 67, 54, 0.3); color: #ef9a9a;">
            <q-icon name="error_outline" color="negative" size="sm" />
            <div class="text-caption">
              <strong>Error:</strong> {{ ingestResult.error || 'Unable to parse valid statblock JSON from input.' }}
            </div>
          </div>
        </div>
      </q-card-section>

      <q-separator />

      <q-card-actions align="right" class="q-pa-md" style="background: rgba(255, 255, 255, 0.04); border-top: 1px solid rgba(255, 255, 255, 0.1);">
        <q-btn flat label="Cancel" color="grey-5" v-close-popup />
        <q-btn
          unelevated
          color="primary"
          label="Apply to Monster Sheet"
          icon="check"
          :disable="!ingestResult.success || !ingestResult.monster"
          @click="applyIngestedMonster"
        />
      </q-card-actions>
    </q-card>
  </q-dialog>
</template>

<script lang="ts">
import { computed, defineComponent, ref } from 'vue'
import { useQuasar } from 'quasar'
import { ingestAiStatblock } from 'src/core/usecases/IngestAiStatblock'
import { useMonsterStore } from 'src/stores/monster-store'
import { useHistoryStore } from 'src/stores/history-store'
import {
  SAMPLE_AI_STATBLOCK_ARCHMAGE,
  SAMPLE_AI_STATBLOCK_DRAGON,
} from './sampleAiPrompts'

export default defineComponent({
  name: 'AiIngestDialog',
  props: {
    modelValue: {
      type: Boolean,
      default: false,
    },
  },
  emits: ['update:modelValue'],
  setup(props, { emit }) {
    const $q = useQuasar()
    const rawInput = ref('')
    const monsterStore = useMonsterStore()
    const historyStore = useHistoryStore()

    const isOpen = computed({
      get: () => props.modelValue,
      set: (val: boolean) => emit('update:modelValue', val),
    })

    const ingestResult = computed(() => {
      if (!rawInput.value.trim()) {
        return { success: false, issuesFixed: 0 }
      }
      return ingestAiStatblock(rawInput.value)
    })

    const loadSample = (type: 'dragon' | 'archmage') => {
      if (type === 'dragon') {
        rawInput.value = SAMPLE_AI_STATBLOCK_DRAGON
      } else {
        rawInput.value = SAMPLE_AI_STATBLOCK_ARCHMAGE
      }
    }

    const applyIngestedMonster = () => {
      if (ingestResult.value.success && ingestResult.value.monster) {
        historyStore.pushSnapshot('Before AI Ingestion')
        monsterStore.$patch(ingestResult.value.monster as any)
        historyStore.pushSnapshot(`AI Ingest: ${ingestResult.value.monster.name}`)

        $q.notify({
          message: `Successfully ingested "${ingestResult.value.monster.name}"!`,
          type: 'positive',
          icon: 'check_circle',
        })

        isOpen.value = false
      }
    }

    return {
      isOpen,
      rawInput,
      ingestResult,
      loadSample,
      applyIngestedMonster,
    }
  },
})
</script>

